"""
Generate the configs of the revision experiments from the existing v7 configs.

Each new config differs from its source only in the keys listed below, and
the script prints those differences so they can be checked by eye.

  C5..C9  protocol C with partition seeds 42..46 (the seeds that protocol A
          uses for its first five partitions); source v7_C0_fixed.yaml
  F       FedAvg GCN and FedAvg MLP under the random partition (protocol B)
          at budget 2; sources v7_D_budget.yaml / v7_E_budget_mlp.yaml
  G       protocol A at budget 2 without the 72 aggregated features
          (93 local features only), GCN and MLP, centralized and FedAvg
  C10..C24  protocol C with partition seeds 47..61, which completes the
          20 x 20 matrix of (partition seed, training seed) for seeds 42..61;
          protocol A is its diagonal
  T*      Soft only, softmax temperature 0.25, 1 or 2 instead of 0.5, on the
          ten fixed partitions C0..C9 (FedProto is the limit of infinite
          temperature)

    python tools/make_revision_configs.py
"""
import copy
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CFG = ROOT / "configs"
HEADER = "# Generated by tools/make_revision_configs.py\n"


def load(name):
    return yaml.safe_load((CFG / name).read_text(encoding="utf-8"))


def variants(cfg, names):
    by_name = {v["name"]: v for v in cfg["experiment"]["variants"]}
    return [copy.deepcopy(by_name[n]) for n in names]


def write(name, cfg, source):
    def flat(d, p=""):
        out = {}
        for k, v in d.items():
            if isinstance(v, dict):
                out.update(flat(v, p + k + "."))
            elif k != "variants":
                out[p + k] = v
        return out
    a, b = flat(source), flat(cfg)
    diff = {k: (a.get(k), b.get(k)) for k in sorted(set(a) | set(b)) if a.get(k) != b.get(k)}
    names = [v["name"] for v in cfg["experiment"]["variants"]]
    (CFG / name).write_text(HEADER + yaml.safe_dump(cfg, allow_unicode=True, sort_keys=False),
                            encoding="utf-8")
    print(f"{name}: {diff} | variants={names}")


def main():
    c0 = load("v7_C0_fixed.yaml")
    for k, seed in enumerate(range(42, 47), start=5):
        cfg = copy.deepcopy(c0)
        cfg["partition"]["fixed_partition_seed"] = seed
        write(f"v7_C{k}_fixed.yaml", cfg, c0)

    d, e = load("v7_D_budget.yaml"), load("v7_E_budget_mlp.yaml")

    g = copy.deepcopy(d)
    g["partition"]["strategy"] = "random_node"
    g["experiment"]["variants"] = variants(d, ["FedAvg_GCN"]) + variants(e, ["FedAvg_MLP"])
    write("v7_F_random_budget.yaml", g, d)

    h = copy.deepcopy(d)
    h["data"]["use_aggregated_features"] = False
    h["experiment"]["variants"] = (variants(d, ["Centralized_GCN", "FedAvg_GCN"])
                                   + variants(e, ["Centralized_MLP", "FedAvg_MLP"]))
    write("v7_G_local_features_budget.yaml", h, d)

    for k, seed in enumerate(range(47, 62), start=10):
        cfg = copy.deepcopy(c0)
        cfg["partition"]["fixed_partition_seed"] = seed
        write(f"v7_C{k}_fixed.yaml", cfg, c0)

    pseeds = list(range(0, 5)) + list(range(42, 47))
    for tag, temp in [("T025", 0.25), ("T1", 1.0), ("T2", 2.0)]:
        for k, seed in enumerate(pseeds):
            cfg = copy.deepcopy(c0)
            cfg["partition"]["fixed_partition_seed"] = seed
            cfg["selection"]["soft_temperature"] = temp
            cfg["fed"]["aggregation_temperature"] = temp
            cfg["experiment"]["variants"] = variants(c0, ["FedGNN_Soft_GCN"])
            write(f"v7_{tag}_C{k}.yaml", cfg, c0)


if __name__ == "__main__":
    main()
