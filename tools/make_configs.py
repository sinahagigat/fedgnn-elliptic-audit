"""
Generate the v7 experiment configs from the v6a config that produced the
paper's runs A, B and C (configs/legacy/run_v6a_20seeds.yaml).

Every v7 config differs from the legacy one only in the keys set below, and
the script prints those differences so they can be checked by eye.

    python tools/make_configs.py
"""
import copy
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
LEGACY = ROOT / "configs" / "legacy" / "run_v6a_20seeds.yaml"
OUT = ROOT / "configs"

base = yaml.safe_load(LEGACY.read_text(encoding="utf-8"))

# ---------------------------------------------------------------- common v7
common = {
    ("experiment", "version"): "7.0.0",
    ("experiment", "tag"): "v7.0.0",
    ("experiment", "save_checkpoints"): False,   # v6a runs used False too
    # "auto" picks the GPU when present, otherwise the CPU; the device is
    # excluded from the config hash, so CPU and GPU jobs share one hash
    ("experiment", "device"): "auto",
    ("experiment", "deterministic"): True,
    ("experiment", "eval_local"): True,
    ("experiment", "eval_tuned_threshold"): True,
    ("experiment", "save_predictions"): True,
    # no payload protection or secure aggregation is applied in any reported
    # run (the earlier v6a runs also exchanged the raw payload)
    ("virtual", "protection"): "none",
    ("privacy", "secure_agg_enabled"): False,
    # the optional compiled extension is not used; the NumPy implementation runs
    ("rust", "use_rust"): False,
}

GCN_VARIANTS = [v["name"] for v in base["experiment"]["variants"]]
FED_GCN_VARIANTS = [n for n in GCN_VARIANTS if not n.startswith("Centralized")]


def mlp_variant(name, algorithm):
    """Graph-free control: identical to the GCN variant except arch=mlp."""
    src = next(v for v in base["experiment"]["variants"]
               if v["algorithm"] == algorithm and v["arch"] == "gcn")
    v = copy.deepcopy(src)
    v["name"] = name
    v["arch"] = "mlp"
    v["model_overrides"]["arch"] = "mlp"
    v["description"] = "Graph-free control (edges ignored)."
    v["tags"] = ["control", "no_graph"]
    return v


def build(changes, variants_keep=None, extra_variants=()):
    cfg = copy.deepcopy(base)
    for (sect, key), val in {**common, **changes}.items():
        cfg.setdefault(sect, {})[key] = val
    vs = cfg["experiment"]["variants"]
    if variants_keep is not None:
        vs = [v for v in vs if v["name"] in variants_keep]
    vs = vs + list(extra_variants)
    cfg["experiment"]["variants"] = vs
    return cfg


def flat(d, p=""):
    out = {}
    for k, v in d.items():
        if isinstance(v, dict):
            out.update(flat(v, f"{p}{k}."))
        elif k != "variants":
            out[f"{p}{k}"] = v
    return out


MLP = [mlp_variant("Centralized_MLP", "centralized"), mlp_variant("FedAvg_MLP", "fedavg")]

configs = {
    # A: the paper's primary protocol, plus two graph-free controls
    "v7_A_louvain.yaml": build({}, extra_variants=MLP),
    # B: random node partition
    "v7_B_random.yaml": build({("partition", "strategy"): "random_node"}, extra_variants=MLP),
    # D: training budget, otherwise identical to A (GCN variants only)
    "v7_D_budget.yaml": build({("fed", "num_rounds"): 300, ("fed", "local_epochs"): 5}),
}
# E: graph-free controls at the D budget (added after D showed that the
# centralized GCN was under-trained at the A budget)
configs["v7_E_budget_mlp.yaml"] = build({("fed", "num_rounds"): 300, ("fed", "local_epochs"): 5},
                                        variants_keep=[], extra_variants=MLP)
# C0..C4: five different fixed Louvain partitions (C0 = the paper's run C)
for k in range(5):
    configs[f"v7_C{k}_fixed.yaml"] = build(
        {("partition", "repartition_per_seed"): False, ("partition", "fixed_partition_seed"): k},
        variants_keep=FED_GCN_VARIANTS,
    )

legacy_flat = flat(base)
for name, cfg in configs.items():
    (OUT / name).write_text(
        "# Generated by tools/make_configs.py from configs/legacy/run_v6a_20seeds.yaml\n"
        + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True),
        encoding="utf-8")
    f = flat(cfg)
    diffs = {k: (legacy_flat.get(k, "<new>"), v) for k, v in f.items() if legacy_flat.get(k, "<new>") != v}
    names = [v["name"] for v in cfg["experiment"]["variants"]]
    print(f"\n{name}: {len(names)} variants x {len(cfg['experiment']['seeds'])} seeds")
    for k, (a, b) in sorted(diffs.items()):
        print(f"   {k}: {a} -> {b}")
    print("   variants:", ", ".join(names))
